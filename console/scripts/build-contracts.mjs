// Copies /contracts/*.json into server/contracts.generated.ts and install/install.sh into
// server/installScript.generated.ts, so the deployed console (root directory = console) carries them.
//   node scripts/build-contracts.mjs          write the file
//   node scripts/build-contracts.mjs --check  exit 1 if the file is stale
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const read = (f) => JSON.parse(readFileSync(join(here, '..', '..', 'contracts', f), 'utf8'));
const out =
  '// GENERATED by scripts/build-contracts.mjs from /contracts. Do not edit; run `npm run contracts:build`.\n' +
  `export const snapshotV1: any = ${JSON.stringify(read('snapshot.v1.schema.json'), null, 2)};\n\n` +
  `export const desiredConfigV1: any = ${JSON.stringify(read('desired-config.v1.schema.json'), null, 2)};\n`;
const installOut =
  '// GENERATED by scripts/build-contracts.mjs from install/install.sh. Do not edit; run `npm run contracts:build`.\n' +
  `export const INSTALL_SCRIPT = ${JSON.stringify(readFileSync(join(here, '..', 'install', 'install.sh'), 'utf8'))};\n`;

const targets = [
  [join(here, '..', 'server', 'contracts.generated.ts'), out],
  [join(here, '..', 'server', 'installScript.generated.ts'), installOut],
];

for (const [target, content] of targets) {
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(target, 'utf8'); } catch { /* missing counts as stale */ }
    if (current !== content) { console.error(`${target} is stale: run \`npm run contracts:build\``); process.exit(1); }
  } else {
    writeFileSync(target, content);
  }
}
